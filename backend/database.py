def connect() -> psycopg.Connection:
    # dict_row makes rows behave like dicts: row["name"], dict(row).
    return psycopg.connect(get_settings().database_url, row_factory=dict_row, connect_timeout=5)


@contextmanager
def get_connection():
    """Yield a connection, commit on success, roll back on error, always close."""
    connection = connect()
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def drop_tables(connection: psycopg.Connection) -> None:
    connection.execute("DROP TABLE IF EXISTS reservations, properties, schema_meta")


def insert_properties(connection: psycopg.Connection, rows) -> None:
    """Insert properties with explicit ids, then move the id counter past them.

    Without the setval, the next property created without an id would get id 1
    and fail on the primary key.
    """
    with connection.cursor() as cursor:
        cursor.executemany(
            """
            INSERT INTO properties
                (id, name, location, property_type, bedrooms, max_guests, nightly_rate)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            """,
            rows,
        )
    connection.execute(
        "SELECT setval(pg_get_serial_sequence('properties', 'id'), "
        "(SELECT MAX(id) FROM properties))"
    )


def initialize_database(seed: bool | None = None) -> None:
    if seed is None:
        seed = get_settings().seed_demo_data

    with get_connection() as connection:
        connection.execute("SELECT pg_advisory_xact_lock(%s)", (SCHEMA_LOCK_ID,))

        has_meta = connection.execute(
            "SELECT to_regclass('schema_meta') IS NOT NULL AS present"
        ).fetchone()["present"]
        version = None
        if has_meta:
            row = connection.execute("SELECT version FROM schema_meta").fetchone()
            version = row["version"] if row else None
        if version != SCHEMA_VERSION:
            drop_tables(connection)

        connection.execute(SCHEMA)
        connection.execute("DELETE FROM schema_meta")
        connection.execute("INSERT INTO schema_meta (version) VALUES (%s)", (SCHEMA_VERSION,))

        is_empty = connection.execute("SELECT COUNT(*) AS n FROM properties").fetchone()["n"] == 0
        if seed and is_empty:
            _seed_demo_data(connection)


def _seed_demo_data(connection: psycopg.Connection, today: date | None = None) -> None:
    """Insert demo properties and ~6 months of non-overlapping bookings around today.

    Dates are relative to today so the dashboard always has current data.
    A fixed random seed keeps the output the same for a given day.
    """
    today = today or date.today()
    rng = random.Random(42)

    insert_properties(connection, DEMO_PROPERTIES)

    rows = []
    for property_id, _, _, _, _, max_guests, rate in DEMO_PROPERTIES:
        cursor = today - timedelta(days=170)
        while cursor < today + timedelta(days=35):
            cursor += timedelta(days=rng.randint(1, 8))
            nights = rng.randint(2, 5)
            check_in, check_out = cursor, cursor + timedelta(days=nights)
            cursor = check_out

            channel = rng.choices(["Airbnb", "Vrbo", "Direct"], weights=[55, 28, 17])[0]
            roll = rng.random()
            if roll < 0.08:
                status = "Cancelled"
            elif check_in > today and roll < 0.35:
                status = "Pending"
            else:
                status = "Confirmed"

            rows.append((
                property_id,
                rng.choice(DEMO_GUESTS),
                channel,
                check_in,
                check_out,
                rng.randint(1, max_guests),
                status,
                nights * rate,
            ))

    with connection.cursor() as db_cursor:
        db_cursor.executemany(
            """
            INSERT INTO reservations
                (property_id, guest_name, channel, check_in, check_out, guests, status, total_amount)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
            """,
            rows,
        )


if __name__ == "__main__":
    initialize_database()
    with get_connection() as conn:
        properties = conn.execute("SELECT COUNT(*) AS n FROM properties").fetchone()["n"]
        reservations = conn.execute("SELECT COUNT(*) AS n FROM reservations").fetchone()["n"]
    print(f"Database ready at: {get_settings().database_url.rsplit('@', 1)[-1]}")
    print(f"Properties: {properties}")
    print(f"Reservations: {reservations}")
